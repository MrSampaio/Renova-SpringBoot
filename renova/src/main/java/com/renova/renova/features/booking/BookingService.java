    public boolean finalizeBooking(BookingRequest request) {
        Connection conn = null;
        CallableStatement bookingStmt = null;
        CallableStatement itemsStmt = null;

        Booking booking = request.getBooking();
        ArrayList<Product> cart = request.getBasket();

        // Safety check: stops the code if the JSON is incomplete
        if (booking == null || cart == null || cart.isEmpty()) {
            throw new IllegalArgumentException("Booking or cart data is empty or invalid.");
        }

        try {
            conn = ConexaoMySql.getConn(ConexaoMySql.login, ConexaoMySql.senha);

            // disables auto-commit
            conn.setAutoCommit(false);

            String bookingSql = "{CALL PROC_CREATE_BOOKING(?, ?, ?, ?)}";
            bookingStmt = conn.prepareCall(bookingSql);

            bookingStmt.setString(1, booking.getUserId());
            bookingStmt.setDouble(2, booking.getTotalAmount());
            bookingStmt.setString(3, booking.getPaymentMethod());

            // the 4th parameter is an OUTPUT (OUT) parameter of type String (the generated UUID)
            bookingStmt.registerOutParameter(4, java.sql.Types.VARCHAR);

            bookingStmt.execute();

            // gets the id generated by the procedure
            String generatedBookingId = bookingStmt.getString(4);

            String itemsSql = "{CALL PROC_INSERT_BOOKING_ITEM(?, ?)}";
            itemsStmt = conn.prepareCall(itemsSql);

            for (Product product : cart) {
                itemsStmt.setString(1, generatedBookingId);
                itemsStmt.setString(2, product.getProductId());

                itemsStmt.executeUpdate(); // runs the procedure for every product
            }

            // everything went fine, commit to the database
            conn.commit();
            return true;

        } catch (SQLException e) {
            // something went wrong
            try {
                if (conn != null) {
                    conn.rollback();
                }
            } catch (SQLException rollbackEx) {
                System.out.println("Critical error while attempting rollback: " + rollbackEx.getMessage());
            }
            throw new RuntimeException("Error finalizing booking. Purchase cancelled! " + e.getMessage());

        } finally {
            try {
                if (bookingStmt != null) {
                    bookingStmt.close();
                }
                if (itemsStmt != null) {
                    itemsStmt.close();
                }
                if (conn != null) {
                    conn.setAutoCommit(true);
                    new ConexaoMySql().desconectar();
                }
            } catch (SQLException e) {
                System.out.println("Error closing connection: " + e.getMessage());
            }
        }
    }

    public ArrayList<Booking> listBookingsByUser(String userId) {

        Connection conn = null;
        CallableStatement stmt = null;
        ResultSet resultSet = null;

        String sql = "{CALL PROC_LIST_BOOKINGS_BY_USER(?)}";


        try {
            ConexaoMySql dbConnection = new ConexaoMySql();

            conn = ConexaoMySql.getConn(ConexaoMySql.login, ConexaoMySql.senha);
            stmt = conn.prepareCall(sql);

            ArrayList<Booking> bookings = new ArrayList<>();

            stmt.setString(1, userId);
            resultSet = stmt.executeQuery();

            while (resultSet.next()) {

                Booking booking = new Booking();

                booking.setBookingId(resultSet.getString("booking_id"));
                booking.setTotalAmount(resultSet.getDouble("total_amount"));
                booking.setPaymentMethod(resultSet.getString("payment_method"));

                java.sql.Timestamp bookingTimestamp = resultSet.getTimestamp("booking_date");
                if (bookingTimestamp != null) {
                    booking.setBookingDate(bookingTimestamp.toLocalDateTime());
                }

                // For DATE (expiration date). Formatting now happens in Booking via @JsonFormat.
                java.sql.Date expirationDate = resultSet.getDate("expiration_date");
                if (expirationDate != null) {
                    booking.setExpirationDate(expirationDate.toLocalDate());
                }

                booking.setStatus(resultSet.getString("status"));
                bookings.add(booking);
            }

            if (!bookings.isEmpty()) {
                System.out.println("Bookings listed successfully.");
            } else {
                System.out.println("Error listing bookings.");
            }

            return bookings;

        } catch (SQLException e) {
            throw new RuntimeException("Database error while listing bookings: " + e.getMessage());

        } finally {
            try {
                if (stmt != null) {
                    stmt.close();
                }
                if (conn != null) {
                    new ConexaoMySql().desconectar();
                }
                if (resultSet != null) {
                    resultSet.close();
                }

            } catch (SQLException e) {
                System.out.println("Failed to close the database connection - " + e.getMessage());
            }
        }
    }

